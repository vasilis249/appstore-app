#!/usr/bin/env python3
"""Course catalogs (<uni>.json) → one idempotent migration that upserts public.courses.

Usage: python3 supabase/data/courses/to_sql.py <out.sql>   (all *.json next to this file)
A course's id is md5(department|semester|name) as a uuid, so re-importing keeps the ids (and the files on them).
"""
import glob, hashlib, json, os, sys, uuid

HERE = os.path.dirname(os.path.abspath(__file__))


def q(s):
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"


def course_id(dept, semester, name):
    return str(uuid.UUID(hashlib.md5(f"{dept}|{semester or ''}|{name}".encode()).hexdigest()))


def rows():
    for path in sorted(glob.glob(os.path.join(HERE, "*.json"))):
        data = json.load(open(path, encoding="utf-8"))
        for dept, d in data["departments"].items():
            for pos, c in enumerate(d["courses"]):
                groups = "ARRAY[" + ",".join(q(g) for g in c.get("groups") or []) + "]::text[]"
                yield (f"({q(course_id(dept, c['semester'], c['name']))}, {q(data['university'])}, {q(dept)}, "
                       f"{q(c.get('code'))}, {q(c['name'])}, {c['semester'] if c['semester'] is not None else 'NULL'}, "
                       f"{q(c['kind'])}, {groups}, {pos})")


def main(out):
    vals = list(rows())
    assert len(vals) == len({v.split(",")[0] for v in vals}), "duplicate course ids"
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- Generated by supabase/data/courses/to_sql.py from supabase/data/courses/*.json — edit those.\n")
        for i in range(0, len(vals), 500):
            f.write("INSERT INTO public.courses (id, university_id, department_id, code, name, semester, kind, groups, position) VALUES\n")
            f.write(",\n".join(vals[i:i + 500]))
            f.write("\nON CONFLICT (id) DO UPDATE SET code = EXCLUDED.code, kind = EXCLUDED.kind, groups = EXCLUDED.groups,\n"
                    "  position = EXCLUDED.position;\n")
    print(f"{len(vals)} courses → {out}")


if __name__ == "__main__":
    main(sys.argv[1])
